/**
 * 사진 없는 식당·카페 자리를 채우는 메뉴 그림 — 분류(「해장국」「치킨」「디저트카페」)의 낱말로 고른다.
 * 위에서부터 먼저 맞는 것을 쓴다(「해물칼국수」는 국수보다 해산물이 먼저).
 */
const RULES: readonly [RegExp, string][] = [
  [/치킨|닭강정/, "🍗"],
  [/피자/, "🍕"],
  [/햄버거|버거/, "🍔"],
  [/회|횟집|해물|해산물|생선|조개|게|대게|아귀|장어/, "🐟"],
  [/초밥|스시|일식|돈까스|돈가스|라멘/, "🍣"],
  [/국수|면|냉면|칼국수|라면|우동|쌀국수/, "🍜"],
  [/짜장|짬뽕|중식|중국|딤섬|만두/, "🥟"],
  [/고기|구이|갈비|삼겹|불고기|육류|곱창|막창|족발|보쌈/, "🥩"],
  [/국밥|해장국|탕|찌개|전골|순두부/, "🍲"],
  [/분식|떡볶이|김밥/, "🍢"],
  [/양식|파스타|스테이크|이탈리/, "🍝"],
  [/베이커리|빵|제과/, "🥐"],
  [/디저트|케이크|아이스크림|빙수/, "🍰"],
  [/카페|커피|찻집|전통찻집/, "☕"],
];

export function foodEmojiOf(category: string | undefined, kind: "restaurant" | "cafe"): string {
  const found = category ? RULES.find(([words]) => words.test(category)) : undefined;
  return found?.[1] ?? (kind === "cafe" ? "☕" : "🍽️");
}
